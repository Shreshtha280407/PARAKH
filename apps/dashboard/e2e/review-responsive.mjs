import assert from 'node:assert/strict';
import {randomBytes,randomUUID} from 'node:crypto';
import {writeFileSync} from 'node:fs';
import {performance} from 'node:perf_hooks';
import {chromium} from 'playwright';
const base=process.env.OPEN_DASHBOARD_URL??'http://127.0.0.1:18177';
const api=process.env.OPEN_API_URL??'http://127.0.0.1:18178';
// Fixture mutations are confined to the dedicated local browser-test API.
assert.equal(new URL(api).origin,'http://127.0.0.1:18178');
const browser=await chromium.launch({headless:true,...(process.env.P8_CHROME?{executablePath:process.env.P8_CHROME}:{})});
const timings={},checks=[],errors=[];
const pass=name=>{checks.push(name);console.log('PASS '+name)};
try {
 const context=await browser.newContext({viewport:{width:1440,height:1000}});
 const page=await context.newPage();page.on('pageerror',e=>errors.push(e.message));
 const password=randomBytes(24).toString('hex');
 assert.equal((await context.request.post(api+'/reviewer/accounts',{data:{name:'Responsive Review Assessor',email:`responsive-${randomUUID()}@example.invalid`,phone:'9000000000',password,password_acknowledged:true}})).status(),201);
 const enrollment=await context.request.post(api+'/workers/enroll',{data:{device_worker_id:`KP-${randomUUID()}`,enrollment_secret:randomBytes(32).toString('hex'),client_assessment_id:randomUUID(),full_name:'Design Review Worker',phone:'+919876543210',public_name_consent:true}});
 assert.equal(enrollment.status(),200,await enrollment.text());const a=await enrollment.json();
 assert.equal((await context.request.post(`${api}/assessments/${a.id}/submit`,{headers:{'X-Worker-Token':a.worker_token}})).status(),200);
 const csrf=(await context.cookies(api)).find(c=>c.name==='parakh_reviewer_csrf').value;
 assert.equal((await context.request.post(`${api}/reviewer/assessments/${a.id}/start-review`,{headers:{'X-Reviewer-CSRF':csrf}})).status(),200);
 await page.goto(base+'/#/queue');
 await page.getByRole('link',{name:`Open assessment ${a.id}`,exact:true}).waitFor();
 await page.getByRole('link',{name:`Open assessment ${a.id}`,exact:true}).click();
 await page.getByText(/Reviewing as Responsive Review Assessor/).waitFor();
 let historyRequests=0;
 await page.route('**/reviewer/assessments/*/history',async route=>{historyRequests++;await new Promise(r=>setTimeout(r,1200));await route.continue()});
 let start=performance.now();
 await page.getByRole('tab',{name:'Audit & history',exact:true}).click();
 await page.locator('#tab-Audit[aria-selected="true"]').waitFor();
 timings.history_tab_ms=Math.round(performance.now()-start);
 assert.ok(timings.history_tab_ms<500);
 await page.getByText('Loading assessment history…',{exact:true}).waitFor();
 start=performance.now();await page.getByRole('tab',{name:'Scoring',exact:true}).click();
 await page.getByRole('heading',{name:'Performance criteria',exact:true}).waitFor();
 timings.scoring_tab_ms=Math.round(performance.now()-start);assert.ok(timings.scoring_tab_ms<500);
 await page.screenshot({path:'/tmp/parakh-ui-review/scoring-desktop-viewport.png'});
 await page.setViewportSize({width:390,height:844});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.screenshot({path:'/tmp/parakh-ui-review/scoring-mobile-viewport.png'});
 await page.setViewportSize({width:1440,height:1000});
 await page.getByRole('tab',{name:'Audit & history',exact:true}).click();
 await page.locator('.revision-current').waitFor();
 const count=historyRequests;
 await page.getByRole('tab',{name:'Scoring',exact:true}).click();
 await page.getByRole('tab',{name:'Audit & history',exact:true}).click();
 await page.locator('.revision-current').waitFor();assert.equal(historyRequests,count);
 await page.screenshot({path:'/tmp/parakh-ui-review/history-desktop-viewport.png'});
 pass('Tabs respond immediately while history is deliberately delayed; loaded history is reused');
 await page.route('**/public/assessments',async route=>{await new Promise(r=>setTimeout(r,1800));await route.continue()});
 start=performance.now();await page.getByRole('navigation',{name:'Main navigation'}).getByRole('link',{name:'Queue',exact:true}).click();
 await page.getByRole('link',{name:`Open assessment ${a.id}`,exact:true}).waitFor();
 timings.cached_queue_ms=Math.round(performance.now()-start);assert.ok(timings.cached_queue_ms<500);
 pass('Returning to the queue displays cached public rows immediately while refreshing in the background');
 await page.unroute('**/public/assessments');
 const review=await (await context.request.get(`${api}/reviewer/assessments/${a.id}/review`)).json();
 for(const item of review)assert.equal((await context.request.put(`${api}/reviewer/assessments/${a.id}/review`,{headers:{'X-Reviewer-CSRF':csrf},data:{pc_full_id:item.pc_full_id,score_level:3,evidence_status:'DEMONSTRATED',expected_version:0}})).status(),200);
 await page.goto(`${base}/#/assessments/${a.id}`);await page.getByText(/Reviewing as Responsive Review Assessor/).waitFor();
 await page.getByRole('tab',{name:'Decision',exact:true}).click();
 await page.getByRole('checkbox',{name:/I have reviewed all evidence/}).check();
 await page.getByRole('button',{name:'Approve and sign report',exact:true}).click();
 const dialog=page.getByRole('dialog',{name:'Confirm and sign assessment',exact:true});
 await dialog.getByRole('combobox').selectOption('NOT_YET_COMPETENT');
 await dialog.getByLabel('Override reason (required when changing computed outcome)',{exact:true}).fill('Local UI validation of a signed negative recommendation.');
 await dialog.getByLabel('Confirm your password',{exact:true}).fill(password);
 await dialog.getByRole('checkbox',{name:/I explicitly confirm/}).check();
 await dialog.getByRole('button',{name:'Confirm action',exact:true}).click();
 const complete=page.getByRole('dialog',{name:'Report signed — not yet qualified',exact:true});await complete.waitFor();
 await complete.screenshot({path:'/tmp/parakh-ui-review/decision-success.png'});
 await page.getByRole('heading',{name:'Assessment queue',exact:true}).waitFor();
 assert.equal((await (await context.request.get(`${api}/public/assessments/${a.id}`)).json()).outcome,'NOT_YET_COMPETENT');
 await page.getByRole('link',{name:`Open assessment ${a.id}`,exact:true}).locator('xpath=ancestor::tr').getByText('Not yet competent',{exact:true}).waitFor();
 pass('Signing a negative recommendation shows the correct success popup and automatically returns to the queue');
 assert.deepEqual(errors,[]);
 writeFileSync('/tmp/parakh-ui-review/dashboard-responsiveness.json',JSON.stringify({timings_ms:timings,checks,browserErrors:errors},null,2));
 console.log(JSON.stringify({passed:checks.length,timings_ms:timings},null,2));
}finally{await browser.close();}
