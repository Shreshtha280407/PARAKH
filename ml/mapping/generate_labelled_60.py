#!/usr/bin/env python3
"""Generate ml/mapping/data/labelled_60.jsonl -- the SYNTHETIC harness fixture
used by eval.py's --mode harness smoke test (never a field-validation or
IC-1-style agreement claim; see data/README.md).

Three worker archetypes (experienced / partial / unrelated), 20 declarations
each. Each record's expected_match is assigned BY ARCHETYPE DESIGN, not
computed from matcher.match() -- this keeps eval.py's agreement number a real
check instead of a circular one (a generator that asked the matcher for the
label would make 100% agreement meaningless by construction).

Regenerated for match-rules@r2 (Q-1 completion, 2026-10-10): r1's version of
this fixture never answered any CON/N9001 (safety) or CON/N8001/N8002
(teamwork/plan & organise) card, because those cards didn't exist yet. This
version answers them consistently with each archetype's persona.

Run: python3 ml/mapping/generate_labelled_60.py
Then: python3 ml/mapping/eval.py --rules packs/ae-con-q0602/mapping --set ml/mapping/data/labelled_60.jsonl
"""
import json
import random
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from matcher import load_rules  # noqa: E402 -- only used to enumerate known item ids

ROOT = Path(__file__).parent.parent.parent
RULES = load_rules(ROOT / "packs/ae-con-q0602/mapping")
OUT_PATH = Path(__file__).parent / "data" / "labelled_60.jsonl"
HARNESS_MARKER = "HARNESS_ONLY_NOT_FIELD_VALIDATION"

ALL_CARD_IDS = [c["id"] for c in RULES["links"]["cards"]]
ALL_TOOL_IDS = [t["id"] for t in RULES["links"]["tools"]]
ALL_ITEM_IDS = sorted(ALL_CARD_IDS + ALL_TOOL_IDS)

EXPERIENCED_TEXTS = [
    "worked on wiring and earthing at a relative's house",
    "two years helping an electrician on construction sites",
    "did house wiring and panel work regularly",
]
PARTIAL_TEXTS = [
    "mostly helped a mason, sometimes fixed a switch board",
    "no electrical work, mostly painting and cleaning sites",
    "helped out sometimes but mostly did general labour",
]
UNRELATED_TEXTS = [
    "I am a plumber, fix pipes and taps",
    "mason work, laying bricks and plaster",
    "welder, work with steel structures",
]


def archetype_answer(rng, archetype):
    """Per-item answer distribution for one archetype."""
    if archetype == "experienced":
        return rng.choices(["often", "sometimes", "never"], weights=[75, 20, 5])[0]
    if archetype == "partial":
        return rng.choices(["often", "sometimes", "never"], weights=[20, 40, 40])[0]
    return rng.choices(["often", "sometimes", "never"], weights=[2, 13, 85])[0]


def build_record(rng, archetype, idx, expected_match, texts):
    answers = {item_id: archetype_answer(rng, archetype) for item_id in ALL_ITEM_IDS}
    return {
        "id": f"D{idx:03d}",
        "answers": answers,
        "free_text": rng.choice(texts),
        "expected_match": expected_match,
        "harness_marker": HARNESS_MARKER,
    }


def main():
    rng = random.Random(4242)
    records = []
    idx = 1
    for _ in range(20):
        records.append(build_record(rng, "experienced", idx, "appropriate_match", EXPERIENCED_TEXTS))
        idx += 1
    for _ in range(20):
        records.append(build_record(rng, "partial", idx, "partial_match", PARTIAL_TEXTS))
        idx += 1
    for _ in range(20):
        records.append(build_record(rng, "unrelated", idx, "not_appropriate_match", UNRELATED_TEXTS))
        idx += 1

    header = (
        "// SYNTHETIC fixture (see ml/mapping/data/README.md). Not real worker data -- a real\n"
        "// independent assessor-agreement study is out of scope for Q-1/P-3 entirely (see\n"
        "// docs/gates/IC1A.md), not merely deferred on this file.\n"
        "// Generated by ml/mapping/generate_labelled_60.py -- do not hand-edit.\n"
    )
    with OUT_PATH.open("w", encoding="utf-8") as f:
        f.write(header)
        for r in records:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    print(f"wrote {len(records)} labelled declarations to {OUT_PATH}")


if __name__ == "__main__":
    main()
